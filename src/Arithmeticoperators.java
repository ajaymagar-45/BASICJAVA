public class Arithmeticoperators {
    public static final int ai=10;
    public static void main(String[] args) {
        int a=10;
        int b=20;
        //Addition
        System.out.println(a+b);

        //Subtraction
        System.out.println(a-b);

        //Multiplication
        System.out.println(a*b);

        //Division
        System.out.println(a/b);

        //Modulous
        System.out.println(a%b);
        System.out.println(ai);
    }
}
