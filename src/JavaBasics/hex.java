package JavaBasics;

public class hex {
    public static void main(abc[] args) {
        int x=10;
        int y=010;
        int z=010;
        System.out.println(x + "__"+y +"__"+z);
         //hexadecimal
        double d=0xface;
        //octal number in java
        System.out.println(d);
        double m=010.0;
        System.out.println(m);

        //2.2e3=2.2x10^3
        float f=02.2e3f;
        System.out.println(f);
        double n=6.3e4;
        System.out.println(n);
        char ch=89;
        System.out.println(ch);
        char a='\uface';
        System.out.println(a);
       //Binary number
        int g=0b1111;
        System.out.println(g);
        //use of underscore in  number
        double q=123_6_67.4_66;
        System.out.println(q);


    }

}
